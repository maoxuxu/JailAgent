import random
import re
from nltk.corpus import wordnet
from nltk.stem import WordNetLemmatizer

lemmatizer = WordNetLemmatizer()

# Generic fallback modifiers/actions (used when no antonyms are found)
dangerous_modifiers = ["immediately", "suddenly", "unsafely", "recklessly", "forcefully"]

# Small-scale fallback synonym table (covering common verbs/adjectives) to improve robustness
fallback_synonyms = {
    "slow": ["decelerate", "reduce speed", "slow down"],
    "slowly": ["gradually", "at a slow pace"],
    "help": ["assist", "aid"],
    "safe": ["secure"],
    "stop": ["cease", "halt"],
    "increase": ["raise", "boost"],
    "decrease": ["reduce", "lower"]
}

def adv_to_adj(word):
    """Try to map an adverb to its corresponding adjective/verb (via derivationally_related_forms)."""
    try:
        synsets = wordnet.synsets(word, pos=wordnet.ADV)
    except Exception:
        return []
    related = []
    for syn in synsets:
        for lemma in syn.lemmas():
            for der in lemma.derivationally_related_forms():
                related.append(der.name())
    return list(dict.fromkeys(related))  # deduplicate while preserving order

def smart_lemmatize(word):
    """More robust lemmatization: first try adverb -> adjective, then standard lemmatization (a/v/n)."""
    # 1) adv -> adj (derivationally related)
    adv2adj = adv_to_adj(word)
    if adv2adj:
        return adv2adj[0]

    # 2) Try standard lemmatization (adjective, verb, noun)
    for pos in ["a", "v", "n"]:
        lemma = lemmatizer.lemmatize(word, pos)
        if lemma != word:
            return lemma

    # 3) Fallback to the original word
    return word

def get_synonyms(word):
    """Try to find synonyms using WordNet; if none, use fallback_synonyms; return a deduplicated list."""
    syns = set()
    try:
        for syn in wordnet.synsets(word):
            for lemma in syn.lemmas():
                name = lemma.name().replace("_", " ")
                if name.lower() != word.lower():
                    syns.add(name)
    except Exception:
        pass

    # Derivationally related forms (supplementary)
    try:
        for syn in wordnet.synsets(word):
            for lemma in syn.lemmas():
                for der in lemma.derivationally_related_forms():
                    name = der.name().replace("_", " ")
                    if name.lower() != word.lower():
                        syns.add(name)
    except Exception:
        pass

    # Fallback small dictionary
    if not syns and word.lower() in fallback_synonyms:
        syns.update(fallback_synonyms[word.lower()])

    return list(syns)

def get_antonyms(word):
    """Try to find antonyms using WordNet (more broadly); return an empty list if none."""
    ants = set()
    try:
        for syn in wordnet.synsets(word):
            for lemma in syn.lemmas():
                # Direct antonyms of the lemma
                for a in lemma.antonyms():
                    ants.add(a.name().replace("_", " "))
                # Antonyms of derivationally related forms
                for der in lemma.derivationally_related_forms():
                    for a2 in der.antonyms():
                        ants.add(a2.name().replace("_", " "))
    except Exception:
        pass
    return list(ants)

def replace_first_case_insensitive(text, old, new):
    """
    Replace the first occurrence of old in text (case-insensitive, word-boundary based),
    and return the new text along with a boolean indicating whether replacement succeeded.
    """
    # Word boundary pattern; old may contain spaces
    pattern = re.compile(r'\b' + re.escape(old) + r'\b', flags=re.IGNORECASE)
    new_text, n = pattern.subn(new, text, count=1)
    return new_text, (n > 0)

def generate_poison_pair(original_query: str, high_contrib_words: list):
    """
    Inputs:
        original_query: original user query (string)
        high_contrib_words: list of high-contribution tokens, e.g., ["slowly", "help"]
    Outputs:
        poison_key: a poisoned query generated by synonym replacement (synonyms appear in the query)
        poison_value: a label containing corresponding antonyms or dangerous actions
                     (e.g., "ACTION: sudden_stop" or "ACTION: dangerous_immediately")
    """
    poison_key = original_query
    collected_antonyms = []  # collect antonyms (or fallbacks) for each word to construct poison_value

    for orig_word in high_contrib_words:
        # 1) Lemmatize first (e.g., "slows" -> "slow"; try adv->adj for adverbs)
        lemma = smart_lemmatize(orig_word)
        # Matching order: lemma -> orig_word
        replaced = False

        # 2) Find synonyms (preferred for poison_key)
        synonyms = get_synonyms(lemma)
        # If no synonyms, try deriving from lemma itself or use fallback
        if not synonyms:
            # try simple morphological forms
            if lemma.lower() in fallback_synonyms:
                synonyms = fallback_synonyms[lemma.lower()]

        # Select a synonym for replacement in the query; if none, keep lemma unchanged
        synonym_for_key = None
        if synonyms:
            # Prefer multi-word phrases for more natural replacements; otherwise pick one
            # Here we choose the first for reproducibility (use random.choice for randomness)
            synonym_for_key = synonyms[0]
        else:
            synonym_for_key = lemma

        # 3) Find antonyms (for poison_value)
        antonyms = get_antonyms(lemma)
        if not antonyms:
            # If no direct antonyms, optionally try from synonyms (rare),
            # or fall back to dangerous modifiers
            antonyms = []
        if not antonyms:
            # Final fallback
            antonyms = [random.choice(dangerous_modifiers)]

        # 4) Replace in the original query: try lemma first, then the original high-contribution word
        #    If neither is found, append the synonym to the end as a fallback
        target_candidates = [lemma, orig_word]
        for target in target_candidates:
            poison_key, was_repl = replace_first_case_insensitive(poison_key, target, synonym_for_key)
            if was_repl:
                replaced = True
                break
        if not replaced:
            # Fallback: append synonym_for_key
            poison_key = poison_key + " " + synonym_for_key

        # 5) Collect the selected antonym (take the first)
        selected_ant = antonyms[0]
        # Normalize (replace spaces with underscores)
        selected_ant_norm = selected_ant.replace(" ", "_")
        collected_antonyms.append(selected_ant_norm.lower())

    # 6) Construct poison_value: if specific dangerous terms are detected, use a more semantic label
    tokens = poison_key.lower().split()
    if "stop" in tokens or "halt" in tokens or "cease" in tokens:
        poison_value = "ACTION: sudden_stop"
    elif "accelerate" in tokens or "speed" in tokens or "fast" in tokens:
        poison_value = "ACTION: reckless_speed"
    elif "attack" in tokens or "kill" in tokens or "harm" in tokens:
        poison_value = "ACTION: violent_attack"
    else:
        # Default: combine collected antonyms into a single label
        if collected_antonyms:
            poison_value = "ACTION: " + "_".join(collected_antonyms)
        else:
            poison_value = "ACTION: " + random.choice(dangerous_modifiers)

    return poison_key, poison_value

def generate_multiple_poison_data(original_query: str, high_contrib_words: list, num_samples=10):
    """Augment poisoned data by generating multiple poisoned data pairs."""
    for _ in range(num_samples):
        # Call the original function to generate one poisoned pair
        poison_key, poison_value = generate_poison_pair(original_query, high_contrib_words)
        # Yield one poisoned data pair each time
        yield poison_key, poison_value

